/**
 * Turn a chosen place into a start: back off from the target along the approach heading
 * so the target is straight ahead.
 */
export function startFromPlace(place) {
  const hdg = (place.heading ?? 0) * Math.PI / 180;
  const back = place.back ?? 3000;
  const lat = place.lat * Math.PI / 180 - (back * Math.cos(hdg)) / R_EARTH;
  const lon = place.lon * Math.PI / 180 - (back * Math.sin(hdg)) / (R_EARTH * Math.cos(lat));
  return { lat: lat * 180 / Math.PI, lon: lon * 180 / Math.PI, alt: place.alt ?? 450, heading: place.heading ?? 0 };
}

export const siteToPlace = (row, lang, kind) => ({
  kind,
  name: lang === 'tr' ? row[0] : row[1],
  lat: row[2], lon: row[3], heading: row[4] ?? 0, alt: row[5] ?? 450,
  back: kind === 'nature' ? 4500 : 2500,
});

